/** Canonical SDR state contract. Keeps commercial rules deterministic and outside the generative model. */
const STATES = Object.freeze({
  NEW: 'NEW',
  IDENTIFYING: 'IDENTIFYING',
  QUALIFYING: 'QUALIFYING',
  QUALIFYING_REVENUE: 'QUALIFYING_REVENUE',
  QUALIFYING_PAIN: 'QUALIFYING_PAIN',
  QUALIFYING_ACCEPTANCE: 'QUALIFYING_ACCEPTANCE',
  CNPJ_PENDING: 'CNPJ_PENDING',
  AGUARDANDO_RETORNO_DO_LUIS: 'AGUARDANDO_RETORNO_DO_LUIS',
  MEETING_MODE: 'MEETING_MODE',
  SCHEDULING: 'SCHEDULING',
  AGUARDANDO_CONFIRMACAO_AGENDA: 'AGUARDANDO_CONFIRMACAO_AGENDA',
  CONFIRMED: 'CONFIRMED',
  HUMAN_HANDOFF: 'HUMAN_HANDOFF',
  LOST: 'LOST',
  ERROR_RETRY: 'ERROR_RETRY',
  CLOSED: 'CLOSED'
});

const HUMAN_GATES = new Set([
  STATES.AGUARDANDO_RETORNO_DO_LUIS,
  STATES.AGUARDANDO_CONFIRMACAO_AGENDA
]);

function isHumanGate(status) { return HUMAN_GATES.has(status); }

module.exports = { STATES, HUMAN_GATES, isHumanGate };
